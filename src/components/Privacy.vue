    5. อายุของข้อมูล

        ข้อมูลของผู้ใช้บนเว็บไซต์เปย์มัวจะยังอยู่หากบัญชียังมีการใช้งาน และสามารถยื่นลบบัญชีได้ผ่านอีเมลติดต่อ
        ในส่วนติดต่อเราในหน้านี้ และในอนาคตอาจมีปุ่มเพื่อลบบัญชีให้สะดวกขึ้น

        ข้อมูล IP Address จะไม่ถูกบันทึกลงฐานข้อมูล แต่จะเก็บไว้ในหน่วยความจำ ซึ่งจะรีเซ็ตใหม่ทุกครั้งเมื่อ
        เซิร์ฟเวอร์มีการรีสตาร์ท หรือเมื่อครบ 3 นาทีหลังจากรีเควสมายังเซิร์ฟเวอร์ครั้งล่าสุด
        และในบริการ Cloudflare Logs ที่อยู่ IP จะถูกลบไปภายใน 24 ชั่วโมง

        ข้อมูลธุรกรรมบนบล็อกเชนไม่สามารถลบได้ เนื่องจากเป็นพื้นฐานของระบบ
        สามารถตรวจสอบได้จากบริการ Basescan.org โดยใส่ Transaction Hash

